package ru.genesis.calendar

import android.content.Context
import android.content.SharedPreferences
import androidx.compose.ui.test.junit4.createAndroidComposeRule
import androidx.room.withTransaction
import androidx.test.platform.app.InstrumentationRegistry
import java.util.UUID
import kotlinx.coroutines.runBlocking
import org.junit.Assert.*
import org.junit.Assume.assumeTrue
import org.junit.Rule
import org.junit.Test
import ru.genesis.calendar.auth.CloudAccountSnapshot
import ru.genesis.calendar.data.*

/** These phases are deliberately separated by an external force-stop in the acceptance harness. */
class HabitBackupProcessRecoveryTest {
    @get:Rule val compose = createAndroidComposeRule<StoicheionGestureActivity>()
    private fun ownedScope(uid: String): String {
        check(UUID.fromString(uid).toString() == uid) // Only UUIDs generated by this fixture, never real account IDs.
        return CloudAccountSnapshot.scopeFor(uid)
    }
    private fun guarded(): GenesisApplication {
        assumeTrue(InstrumentationRegistry.getArguments().getString("genesisE5ProcessRecovery") == "true")
        val app = compose.activity.application as GenesisApplication
        check(BuildConfig.DEBUG && app.packageName in setOf("ru.genesis.calendar.ghttps.debug", "ru.genesis.calendar.v313.debug"))
        val recoveryUid = app.getSharedPreferences("e5-process-recovery", Context.MODE_PRIVATE).getString("uid", null)
        check(app.workspaceScope == "internal-validation-v1" || recoveryUid != null && app.workspaceScope == ownedScope(recoveryUid))
        return app
    }
    private suspend fun cleanupOwnedStage(app: GenesisApplication, preferences: SharedPreferences, uid: String, draftId: String?) {
        val scope = ownedScope(uid)
        check(app.workspaceScope == "internal-validation-v1" || app.workspaceScope == scope)
        check(preferences.getString("uid", null) == uid)
        check(preferences.getString("draft", null) == draftId)
        app.database.withTransaction {
            app.database.openHelper.writableDatabase.execSQL("DELETE FROM documents WHERE scope=?", arrayOf(scope))
            app.database.openHelper.writableDatabase.execSQL("DELETE FROM outbox WHERE scope=?", arrayOf(scope))
        }
        // uid/draft were reserved by this pair; every other pre-existing fixture preference is retained.
        check(preferences.edit().remove("uid").remove("draft").commit())
        app.activateAccount(null)
    }
    @Test fun stageBeforeProcessDeath() = runBlocking {
        val app = guarded()
        val preferences = app.getSharedPreferences("e5-process-recovery", Context.MODE_PRIVATE)
        check(app.workspaceScope == "internal-validation-v1") { "Stage requires the original synthetic local workspace" }
        check(!preferences.contains("uid") && !preferences.contains("draft")) { "A prior recovery stage must not be overwritten" }
        val baseline = preferences.all
        val uid = UUID.randomUUID().toString(); val scope = ownedScope(uid)
        app.database.withTransaction {
            app.database.openHelper.readableDatabase.query("SELECT COUNT(*) FROM documents WHERE scope=?", arrayOf(scope)).use {
                check(it.moveToFirst() && it.getLong(0) == 0L) { "Generated recovery scope is not empty" }
            }
            check(app.database.dao().outbox(scope).isEmpty())
        }
        var draftId: String? = null
        // Reserve ownership before changing workspace or writing a draft, without replacing prior metadata.
        try {
            synchronized(preferences) {
                check(!preferences.contains("uid") && !preferences.contains("draft"))
                check(preferences.edit().putString("uid", uid).commit())
            }
            app.activateAccount(uid)
            val service = HabitBackupService(app)
            val text = InstrumentationRegistry.getInstrumentation().context.assets.open("habit-backup-web.json").bufferedReader().use { it.readText() }
            val source = HabitBackups.parse(text).workspace()
            app.database.withTransaction { app.database.dao().putDocument(DocumentRecord(scope, "habits",
                LocalCipher().encrypt(HabitDocument.encode(source.copy(habits = source.habits.map { it.copy(title = "Current " + it.title) })), "$scope/habits"), 1)) }
            assertNull(service.load())
            var draft = service.prepare(text, "После перезапуска.json")
            for (row in draft.preview.habits) draft = service.choose(draft.id, row.id, "copy")
            synchronized(preferences) {
                check(preferences.getString("uid", null) == uid && !preferences.contains("draft"))
                draftId = draft.id
                check(preferences.edit().putString("draft", draft.id).commit())
            }
            assertEquals(baseline, preferences.all.filterKeys { it != "uid" && it != "draft" })
            assertEquals(2, service.load()!!.choices.size)
        } catch (failure: Throwable) {
            cleanupOwnedStage(app, preferences, uid, draftId)
            throw failure
        }
    }
    @Test fun reopenAfterProcessDeathAndApplyExactlyOnce() = runBlocking {
        val app = guarded(); val preferences = app.getSharedPreferences("e5-process-recovery", Context.MODE_PRIVATE)
        val uid = requireNotNull(preferences.getString("uid", null)); val id = requireNotNull(preferences.getString("draft", null))
        val scope = ownedScope(uid)
        val baseline = preferences.all.filterKeys { it != "uid" && it != "draft" }
        try {
            app.activateAccount(uid)
            val service = HabitBackupService(app); val draft = service.load()!!
            assertEquals(id, draft.id); assertEquals("После перезапуска.json", draft.filename)
            assertTrue(draft.choices.values.all { it == "copy" }); assertFalse(draft.stale)
            val before = service.current(); service.apply(id)
            val after = service.current(); assertEquals(4, after.habits.size)
            assertEquals(before.progress, after.progress); assertEquals(before.rewards, after.rewards)
            val document = app.database.dao().document(scope, "habits"); val outbox = app.database.dao().outbox(scope)
            HabitBackupService(app).apply(id)
            assertEquals(document, app.database.dao().document(scope, "habits")); assertEquals(outbox, app.database.dao().outbox(scope))
            assertNull(service.load())
        } finally {
            cleanupOwnedStage(app, preferences, uid, id)
            assertEquals(baseline, preferences.all)
        }
    }
}
