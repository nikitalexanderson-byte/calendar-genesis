function load(name,dependencies={}) {
  const exports={};
  const js=ts.transpileModule(read(name),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
  vm.runInNewContext(js,{exports,Date,Math,Map,Set,Intl,require:(id)=>{
    if(!(id in dependencies))throw Error(`Unexpected runtime dependency ${id}`);
    return dependencies[id];
  }});
  return exports;
}
